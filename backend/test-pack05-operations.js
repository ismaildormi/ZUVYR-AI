'use strict';
const assert=require('node:assert/strict');
const {config,assertVideoOperationAvailable,assertVideoRequestAvailable,providerSupports,inventory}=require('./lib/videoOperationRegistry');
assert.equal(config.version,'pack-05.video-system.v1');
assert.throws(()=>assertVideoOperationAvailable('text_to_video'),e=>e.code==='video_operation_disabled');
const enabled=assertVideoRequestAvailable({operation:'text_to_video',options:{durationSeconds:5,ratio:'16:9',resolution:'480p',fps:16,audio:false,exportFormat:'mp4'}},{env:{PACK066_PAID_EXECUTION_ENABLED:'true'}});
assert.equal(enabled.provider,'replicate');
for(const op of ['image_to_video','edit','extend','subtitles','enhance','export']) assert.throws(()=>assertVideoOperationAvailable(op),e=>e.code==='video_operation_unpriced');
assert.equal(providerSupports('replicate','text_to_video'),true);assert.equal(providerSupports('replicate','image_to_video'),false);assert.equal(providerSupports('unknown','text_to_video'),false);
assert.deepEqual(Object.keys(inventory().operations),Object.keys(config.operations));
console.log('PASS: Pack05/066 gated T2V registry and fail-closed later operations');
